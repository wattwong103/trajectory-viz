"""
One-command demo — ingest the bundled synthetic dataset and (optionally) serve.

    trajectory-viz-demo                 # ingest demo/ → demo/demo.duckdb (first run)
    trajectory-viz-demo --serve         # ingest if needed, then serve on :9999
    trajectory-viz-demo --reset         # force a fresh re-ingest
    trajectory-viz-demo --db-path X.duckdb   # ingest into a custom DB path

The dataset (GPX couriers + GeoJSON buses + POI points around Kichijoji,
Tokyo) is generated by demo/generate_demo_data.py and committed under demo/.
Everything is wired through env vars — PFLOW_VIZ_DB / PFLOW_VIZ_SOURCES /
PFLOW_VIZ_OUTPUT_ROOT — so the ingest path exercised here is exactly the one
`trajectory-viz-ingest` uses.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

# Allow running as `python -m backend.demo` from trajectory-viz/
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

SOURCES_NAME = "sources.demo.yaml"
_FRONTEND_DIST = Path(__file__).resolve().parent.parent / "frontend" / "dist"

EMPTY_DB_HINT = (
    "No trips yet — drop a GPX/GeoJSON/CSV onto the map, run "
    "`trajectory-viz-demo` (then `npm run build` for the map UI), "
    "or `docker compose up --build` for the one-URL demo."
)


def resolve_demo_dir() -> Path:
    """Locate the committed demo/ directory.

    Package-relative first (one level above backend/ — correct for editable
    installs from the repo root), then ./demo under the current working
    directory (covers running from inside a copied source tree).
    """
    pkg_relative = Path(__file__).resolve().parent.parent / "demo"
    if (pkg_relative / SOURCES_NAME).is_file():
        return pkg_relative
    cwd_relative = Path.cwd() / "demo"
    if (cwd_relative / SOURCES_NAME).is_file():
        return cwd_relative
    raise FileNotFoundError(
        f"Cannot locate the demo dataset ({SOURCES_NAME}). Looked in "
        f"{pkg_relative} and {cwd_relative}. Run from the trajectory-viz "
        f"repo, or regenerate with `python demo/generate_demo_data.py`."
    )


def demo_env(db_path: Path, demo_dir: Path | None = None) -> dict[str, str]:
    """Return the env-var mapping for a demo run (does NOT mutate os.environ).

    Kept separate so tests can assert the wiring without side effects.
    """
    demo_dir = demo_dir or resolve_demo_dir()
    db_path = Path(db_path)
    return {
        # Canonical aliases first; legacy PFLOW_* kept for older tooling.
        "TRAJECTORY_VIZ_DB": str(db_path),
        "TRAJECTORY_VIZ_SOURCES": str(demo_dir / SOURCES_NAME),
        "TRAJECTORY_VIZ_OUTPUT_ROOT": str(demo_dir),
        "TRAJECTORY_VIZ_PROFILE": "demo",
        "PFLOW_VIZ_DB": str(db_path),
        "PFLOW_VIZ_SOURCES": str(demo_dir / SOURCES_NAME),
        "PFLOW_VIZ_OUTPUT_ROOT": str(demo_dir),
    }


def db_has_trips(db_path: Path) -> bool:
    """True when `db_path` exists and the trips table has at least one row.

    Used by Docker entrypoint / ensure_demo_db so an empty schema-only DuckDB
    still triggers a demo seed (unless seeding is disabled).
    """
    db_path = Path(db_path).resolve()
    if not db_path.is_file():
        return False

    def _count(conn) -> int | None:
        try:
            tables = {
                r[0]
                for r in conn.execute(
                    "SELECT table_name FROM information_schema.tables "
                    "WHERE table_schema = 'main'"
                ).fetchall()
            }
            if "trips" not in tables:
                return 0
            return int(conn.execute("SELECT COUNT(*) FROM trips").fetchone()[0])
        except Exception:
            return None

    # Prefer the process singleton when it already holds this file — a second
    # DuckDB connect would fail while the write connection is open.
    try:
        import backend.db as _db
        from backend.config import get_viz_db_path

        if _db._connection is not None and get_viz_db_path().resolve() == db_path:
            n = _count(_db._connection)
            if n is not None:
                return n > 0
    except Exception:
        pass

    try:
        import duckdb

        conn = duckdb.connect(str(db_path), read_only=True)
        try:
            n = _count(conn)
            return bool(n and n > 0)
        finally:
            conn.close()
    except Exception:
        return False


def frontend_dist_ready(dist: Path | None = None) -> bool:
    """True when a built frontend (`index.html`) is present for StaticFiles."""
    root = Path(dist) if dist is not None else _FRONTEND_DIST
    return root.is_dir() and (root / "index.html").is_file()


def ui_serve_hint() -> str:
    """Honest next-step text when the API is up but the map UI may be missing."""
    if frontend_dist_ready():
        return (
            "Map UI is bundled — open the serve URL (Docker :8080 / native :9999)."
        )
    return (
        "API-only so far (frontend/dist missing). For the map in one shot use "
        "`docker compose up --build` → http://localhost:8080, or build once with "
        "`cd frontend && npm install && npm run build` then re-serve, or run "
        "`cd frontend && npm run dev` → http://localhost:5173 (Vite HMR)."
    )


def run_demo(db_path: Path, reset: bool = False) -> dict[str, int]:
    """Ingest the demo dataset into `db_path` (unless it already exists and
    `reset` is False). Returns summary counts {trips, waypoints, pois}.

    Reuses backend.ingest.main() via a temporary sys.argv so the demo always
    exercises the real ingest orchestration, banner and all.
    """
    from backend import ingest as _ingest
    from backend.db import get_connection

    env = demo_env(db_path)
    os.environ.update(env)

    # Drop stale singleton so counts (and later serve) hit this db_path.
    import backend.db as _db

    if _db._connection is not None:
        _db._connection.close()
        _db._connection = None

    first_run = not Path(db_path).is_file()
    do_ingest = reset or first_run

    if do_ingest:
        if first_run and not reset:
            print("[DEMO] First run — ingesting the bundled demo dataset...")
        argv = ["trajectory-viz-ingest"]
        if reset:
            argv.append("--reset")
        saved_argv = sys.argv
        sys.argv = argv
        try:
            _ingest.main()
        except SystemExit as e:
            if e.code not in (0, None):
                raise RuntimeError(
                    f"Demo ingest failed (exit {e.code}). See the log above."
                ) from e
        finally:
            sys.argv = saved_argv

    conn = get_connection()
    counts = {
        "trips": conn.execute("SELECT COUNT(*) FROM trips").fetchone()[0],
        "waypoints": conn.execute("SELECT COUNT(*) FROM waypoints").fetchone()[0],
        "pois": conn.execute("SELECT COUNT(*) FROM pois").fetchone()[0],
    }
    return counts


def ensure_demo_db(
    db_path: Path,
    *,
    seed: bool = True,
    reset: bool = False,
) -> dict[str, int]:
    """Ensure `db_path` has demo trips when `seed` is True.

    - seed=True + missing/empty → run_demo (ingest; reset when file exists but empty)
    - seed=False + missing/empty → return zero counts without creating a DB
    - already populated → reuse (unless reset=True)
    """
    db_path = Path(db_path)
    if not seed:
        if db_has_trips(db_path):
            return run_demo(db_path, reset=False)
        return {"trips": 0, "waypoints": 0, "pois": 0}
    if reset or not db_has_trips(db_path):
        # File may exist as schema-only; --reset forces a real ingest.
        return run_demo(db_path, reset=True if db_path.is_file() else reset)
    return run_demo(db_path, reset=False)


def _print_summary(counts: dict[str, int], db_path: Path) -> None:
    print()
    print("=" * 64)
    print("  trajectory-viz demo — ready")
    print("=" * 64)
    print(f"  Trips:      {counts['trips']:>8,}  (couriers gap-split at lunch breaks)")
    print(f"  Waypoints:  {counts['waypoints']:>8,}  (GPX trkpts + GeoJSON coords)")
    print(f"  POIs:       {counts['pois']:>8,}  (stations / malls / parks)")
    print(f"  Database:   {db_path}")


def _print_next_steps(db_path: Path) -> None:
    print()
    print("  Next steps (pick one):")
    print("    • One URL (map + API):   docker compose up --build")
    print("                              → http://localhost:8080")
    print("    • Native map (HMR):      cd frontend && npm run dev")
    print("                              → http://localhost:5173")
    print("    • Native single port:    cd frontend && npm run build")
    print("                              trajectory-viz-demo --serve")
    print("                              → http://127.0.0.1:9999")
    print(f"    • UI status:             {ui_serve_hint()}")
    print("    • Your own data:         docs/DATA_FORMATS.md")
    print("    • Re-ingest:             trajectory-viz-demo --reset")
    print()


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Ingest the bundled demo dataset and optionally serve it."
    )
    parser.add_argument(
        "--db-path",
        type=Path,
        default=None,
        help="DuckDB output path (default: <demo dir>/demo.duckdb).",
    )
    parser.add_argument(
        "--reset",
        action="store_true",
        help="Drop existing tables and re-ingest from scratch.",
    )
    parser.add_argument(
        "--serve",
        action="store_true",
        help="Start the API server (uvicorn on 127.0.0.1:9999) after ingest.",
    )
    parser.add_argument(
        "--ensure",
        action="store_true",
        help=(
            "Seed only when the DB is missing or has zero trips "
            "(used by Docker entrypoint). Implies no serve unless --serve."
        ),
    )
    parser.add_argument(
        "--no-seed",
        action="store_true",
        help="With --ensure: do not ingest; exit 0 even if the DB is empty.",
    )
    args = parser.parse_args()

    demo_dir = resolve_demo_dir()
    db_path = args.db_path or (demo_dir / "demo.duckdb")

    if args.ensure:
        counts = ensure_demo_db(
            db_path, seed=not args.no_seed, reset=args.reset
        )
        if counts["trips"] == 0:
            print(f"[DEMO] Empty DB at {db_path} — {EMPTY_DB_HINT}")
        else:
            _print_summary(counts, db_path)
    else:
        counts = run_demo(db_path, reset=args.reset)
        _print_summary(counts, db_path)

    if args.serve:
        print()
        print(f"  {ui_serve_hint()}")
        print("  Serving the demo — open http://127.0.0.1:9999 (Ctrl+C to stop)")
        if not frontend_dist_ready():
            print(
                "  [WARN] frontend/dist missing — you will see API JSON at /, "
                "not the map. Prefer `docker compose up --build` or "
                "`npm run build` / `npm run dev`."
            )
        from backend.app import serve

        serve()
    elif not args.ensure:
        _print_next_steps(db_path)


if __name__ == "__main__":
    main()
