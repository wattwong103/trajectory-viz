"""
One-command demo — ingest the bundled synthetic dataset and (optionally) serve.

    trajectory-viz-demo                 # ingest demo/ → demo/demo.duckdb (first run)
    trajectory-viz-demo --serve         # ingest if needed, then serve on :9999
    trajectory-viz-demo --reset         # force a fresh re-ingest
    trajectory-viz-demo --db-path X.duckdb   # ingest into a custom DB path

The dataset (GPX couriers + GeoJSON buses + POI points around Kichijoji,
Tokyo) is generated by demo/generate_demo_data.py and committed under demo/.
Everything is wired through env vars — PFLOW_VIZ_DB / PFLOW_VIZ_SOURCES /
PFLOW_VIZ_OUTPUT_ROOT — so the ingest path exercised here is exactly the one
`trajectory-viz-ingest` uses.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

# Allow running as `python -m backend.demo` from trajectory-viz/
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

SOURCES_NAME = "sources.demo.yaml"


def resolve_demo_dir() -> Path:
    """Locate the committed demo/ directory.

    Package-relative first (one level above backend/ — correct for editable
    installs from the repo root), then ./demo under the current working
    directory (covers running from inside a copied source tree).
    """
    pkg_relative = Path(__file__).resolve().parent.parent / "demo"
    if (pkg_relative / SOURCES_NAME).is_file():
        return pkg_relative
    cwd_relative = Path.cwd() / "demo"
    if (cwd_relative / SOURCES_NAME).is_file():
        return cwd_relative
    raise FileNotFoundError(
        f"Cannot locate the demo dataset ({SOURCES_NAME}). Looked in "
        f"{pkg_relative} and {cwd_relative}. Run from the trajectory-viz "
        f"repo, or regenerate with `python demo/generate_demo_data.py`."
    )


def demo_env(db_path: Path, demo_dir: Path | None = None) -> dict[str, str]:
    """Return the env-var mapping for a demo run (does NOT mutate os.environ).

    Kept separate so tests can assert the wiring without side effects.
    """
    demo_dir = demo_dir or resolve_demo_dir()
    db_path = Path(db_path)
    return {
        "PFLOW_VIZ_DB": str(db_path),
        "PFLOW_VIZ_SOURCES": str(demo_dir / SOURCES_NAME),
        "PFLOW_VIZ_OUTPUT_ROOT": str(demo_dir),
    }


def run_demo(db_path: Path, reset: bool = False) -> dict[str, int]:
    """Ingest the demo dataset into `db_path` (unless it already exists and
    `reset` is False). Returns summary counts {trips, waypoints, pois}.

    Reuses backend.ingest.main() via a temporary sys.argv so the demo always
    exercises the real ingest orchestration, banner and all.
    """
    from backend import ingest as _ingest
    from backend.db import get_connection

    env = demo_env(db_path)
    os.environ.update(env)

    first_run = not Path(db_path).is_file()
    do_ingest = reset or first_run

    if do_ingest:
        if first_run and not reset:
            print("[DEMO] First run — ingesting the bundled demo dataset...")
        argv = ["trajectory-viz-ingest"]
        if reset:
            argv.append("--reset")
        saved_argv = sys.argv
        sys.argv = argv
        try:
            _ingest.main()
        except SystemExit as e:
            if e.code not in (0, None):
                raise RuntimeError(
                    f"Demo ingest failed (exit {e.code}). See the log above."
                ) from e
        finally:
            sys.argv = saved_argv

    conn = get_connection()
    counts = {
        "trips": conn.execute("SELECT COUNT(*) FROM trips").fetchone()[0],
        "waypoints": conn.execute("SELECT COUNT(*) FROM waypoints").fetchone()[0],
        "pois": conn.execute("SELECT COUNT(*) FROM pois").fetchone()[0],
    }
    return counts


def _print_summary(counts: dict[str, int], db_path: Path) -> None:
    print()
    print("=" * 64)
    print("  trajectory-viz demo — ready")
    print("=" * 64)
    print(f"  Trips:      {counts['trips']:>8,}  (couriers gap-split at lunch breaks)")
    print(f"  Waypoints:  {counts['waypoints']:>8,}  (GPX trkpts + GeoJSON coords)")
    print(f"  POIs:       {counts['pois']:>8,}  (stations / malls / parks)")
    print(f"  Database:   {db_path}")


def _print_next_steps(db_path: Path) -> None:
    print()
    print("  Next steps:")
    print("    • Serve the demo:        trajectory-viz-demo --serve")
    print("    • …then open:            http://127.0.0.1:9999")
    print("      (frontend needs `cd frontend && npm run build` once,")
    print("       or `npm run dev` on :5173 for hot-reload dev)")
    print("    • Bring your own data:   docs/DATA_FORMATS.md")
    print("    • Re-ingest from scratch: trajectory-viz-demo --reset")
    print()


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Ingest the bundled demo dataset and optionally serve it."
    )
    parser.add_argument(
        "--db-path",
        type=Path,
        default=None,
        help="DuckDB output path (default: <demo dir>/demo.duckdb).",
    )
    parser.add_argument(
        "--reset",
        action="store_true",
        help="Drop existing tables and re-ingest from scratch.",
    )
    parser.add_argument(
        "--serve",
        action="store_true",
        help="Start the API server (uvicorn on 127.0.0.1:9999) after ingest.",
    )
    args = parser.parse_args()

    demo_dir = resolve_demo_dir()
    db_path = args.db_path or (demo_dir / "demo.duckdb")

    counts = run_demo(db_path, reset=args.reset)
    _print_summary(counts, db_path)

    if args.serve:
        print()
        print("  Serving the demo — open http://127.0.0.1:9999 (Ctrl+C to stop)")
        from backend.app import serve

        serve()
    else:
        _print_next_steps(db_path)


if __name__ == "__main__":
    main()
